package cn.changjiahong.composexmlui

import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import cn.changjiahong.composexmlui.components.TextNodeRenderer
import cn.changjiahong.composexmlui.core.XmlUiException
import cn.changjiahong.composexmlui.node.AttrValue
import cn.changjiahong.composexmlui.node.ColumnNode
import cn.changjiahong.composexmlui.node.Dimension
import cn.changjiahong.composexmlui.node.Node
import cn.changjiahong.composexmlui.node.TextNode
import cn.changjiahong.composexmlui.parser.NodeContext
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNotEquals
import kotlin.test.assertSame
import kotlin.test.assertTrue

/**
 * 注册机制：节点与渲染器分开登记，两表各自可覆盖。
 */
class RegistrationTest {

    private val registry = ComposeXmlUi.createRegistry()

    private fun literal(attr: AttrValue<*>?): Any? = attr?.constant

    // ---------------- id ----------------

    @Test
    fun idFallsBackToAutoGenerated() {
        val root = ComposeXmlUi.parse(
            """<Column><Text value="a"/><Text value="b"/></Column>""",
            registry,
        ) as ColumnNode

        assertTrue(root.id.startsWith("auto_"), root.id)
        val ids = root.children.map { it.id }
        assertTrue(ids.all { it.startsWith("auto_") }, ids.toString())
        assertEquals(2, ids.toSet().size, "自动 id 不能重复")
        assertNotEquals(root.id, ids.first())
    }

    @Test
    fun declaredIdIsPreserved() {
        val root = ComposeXmlUi.parse(
            """<Column id="main"><Text id="title" value="a"/></Column>""",
            registry,
        ) as ColumnNode

        assertEquals("main", root.id)
        assertEquals("title", root.children.single().id)
    }

    // ---------------- 样式属性按节点声明 ----------------

    @Test
    fun styleAttributesAreAcceptedOnStyledNodes() {
        val text = ComposeXmlUi.parse("""<Text value="a" padding="8" width="fill"/>""", registry) as TextNode
        assertEquals(8.dp, literal(text.padding))
        assertEquals(Dimension.Fill, literal(text.width))
    }

    @Test
    fun styleAttributesAreRejectedOnNodesWithoutStyled() {
        val error = assertFailsWith<XmlUiException> {
            ComposeXmlUi.parse("""<If test="true" padding="8"><Then><Text value="a"/></Then></If>""", registry)
        }
        assertEquals("padding", error.attribute)
        assertTrue(error.message!!.contains("不支持"), error.message)
    }

    // ---------------- 两张表的独立覆盖 ----------------

    @Test
    fun subclassNodeFallsBackToParentRenderer() {
        val custom = ComposeXmlUi.createRegistry()
        custom.nodes.register("Text") { RichTextNode(it) }

        val node = custom.parse("""<Text value="a" letterSpacing="2"/>""")
        assertTrue(node is RichTextNode, "标签应造出子类节点")

        // 没有为 RichTextNode 注册渲染器 → 回退到 TextNode 的
        assertTrue(custom.renderers.rendererFor(node) is TextNodeRenderer)
    }

    @Test
    fun replacingRendererAffectsBuiltInNode() {
        val custom = ComposeXmlUi.createRegistry()
        val override = TextNodeRenderer()
        custom.renderers.register(TextNode::class, override)

        val node = custom.parse("""<Text value="a"/>""")
        assertTrue(override === custom.renderers.rendererFor(node))
    }

    @Test
    fun missingRendererReportsNodeType() {
        val custom = ComposeXmlUi.createRegistry()
        custom.nodes.register("Orphan") { OrphanNode(it) }

        val node = custom.parse("<Orphan/>")
        val error = assertFailsWith<XmlUiException> { custom.renderers.rendererFor(node) }
        assertTrue(error.message!!.contains("OrphanNode"), error.message)
    }

    @Test
    fun unregisterOnlyRemovesNodeEntry() {
        val custom = ComposeXmlUi.createRegistry()
        custom.unregister("Text")

        assertTrue(!custom.hasTag("Text"))
        // 渲染器条目仍在：别的标签可能复用同一个节点类型
        assertTrue(custom.renderers.has(TextNode::class))
    }
}

/** 继承内置节点扩展属性：只有 `letterSpacing` 是新的。 */
private class RichTextNode(context: NodeContext) : TextNode(context) {
    val letterSpacing: AttrValue<TextUnit>? = context.attr("letterSpacing")
}

/** 只注册节点、不注册渲染器，用于验证报错信息。 */
private class OrphanNode(context: NodeContext) : Node(context)
